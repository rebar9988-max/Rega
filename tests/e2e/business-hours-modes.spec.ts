import { test, expect } from './fixtures';
import { ADMIN } from './global-setup';
import AxeBuilder from '@axe-core/playwright';

test('hours modes preserve appointment schedules and support compact day overrides', async ({ page }, testInfo) => {
  await page.goto('/de/login?next=%2Fdr');
  await page.getByLabel('E-Mail', { exact: true }).fill(ADMIN.email);
  await page.getByLabel('Passwort', { exact: true }).fill(ADMIN.password);
  await page.getByRole('button', { name: 'Anmelden' }).click();
  await expect(page).toHaveURL(/\/dr$/);
  await page.goto('/dr/businesses/new');
  await page.getByLabel('Name', { exact: true }).fill(`E2E Hours ${Date.now()}`);
  await page.getByRole('combobox', { name: 'Kategorie', exact: true }).selectOption({ label: 'Recht' });
  await page.getByLabel('Straße und Hausnummer').fill('Oranienstraße 1');
  await page.getByLabel('Stadt', { exact: true }).fill('Berlin');
  const group = page.getByRole('radiogroup');
  await group.locator('[value="always"]').check();
  for (const d of ['mon','tue','wed','thu','fri','sat','sun']) await expect(page.getByTestId(`hours-${d}`)).toHaveValue('00:00–24:00');
  await expect(page.getByTestId('hours-mon')).toBeHidden();
  await group.locator('[value="five"]').check();
  await expect(page.getByTestId('hours-mon')).toHaveValue('09:00–17:00');
  await expect(page.getByTestId('hours-sat')).toHaveValue('closed');
  await page.getByTestId('hours-mon').fill('20:00–02:00');
  await group.locator('[value="appointment"]').check();
  await expect(page.getByTestId('hours-mon')).toHaveValue('20:00–02:00');
  await group.locator('[value="custom"]').check();
  await expect(page.getByTestId('hours-mon')).toHaveValue('20:00–02:00');
  await group.locator('[value="appointment"]').check();
  await page.getByTestId('save').click();
  await expect(page.getByTestId('form-notice')).toHaveText('Gespeichert.');
  await page.reload();
  await expect(page.locator('[name="hoursMode"][value="appointment"]')).toBeChecked();
  await expect(page.getByTestId('hours-mon')).toHaveValue('20:00–02:00');
  await group.locator('[value="custom"]').check();
  const panel = group.locator('..');
  await panel.screenshot({ path: testInfo.outputPath('hours-after.png') });
  const accessibility = await new AxeBuilder({ page }).include('[role="radiogroup"]').analyze();
  expect(accessibility.violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.screenshot({ path: testInfo.outputPath('hours-mobile-after.png') });
  await page.context().addCookies([{ name: 'REGA_LOCALE', value: 'ckb', url: 'http://localhost:3111' }]);
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await group.locator('[value="custom"]').check();
  await expect(group).toContainText('هەمیشە کراوەیە');
  await panel.screenshot({ path: testInfo.outputPath('hours-sorani-after.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);

});
